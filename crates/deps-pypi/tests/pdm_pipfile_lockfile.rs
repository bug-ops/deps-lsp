#[test]
fn locate_lockfile_finds_pdm_lock() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("pdm.lock"), PDM_LOCK).unwrap();
    let found = PypiLockParser.locate_lockfile(&manifest_uri(dir.path()));
    assert_eq!(found, Some(dir.path().join("pdm.lock")));
}

#[test]
fn locate_lockfile_finds_pipfile_lock() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("Pipfile.lock"), PIPFILE_LOCK).unwrap();
    let found = PypiLockParser.locate_lockfile(&manifest_uri(dir.path()));
    assert_eq!(found, Some(dir.path().join("Pipfile.lock")));
}

#[test]
fn locate_lockfile_precedence_poetry_uv_pdm_pipfile() {
    let dir = tempfile::tempdir().unwrap();
    let uri = manifest_uri(dir.path());
    for name in ["Pipfile.lock", "pdm.lock", "uv.lock", "poetry.lock"] {
        std::fs::write(dir.path().join(name), "").unwrap();
        assert_eq!(
            PypiLockParser.locate_lockfile(&uri),
            Some(dir.path().join(name)),
            "{name} must win over every later format in precedence order"
        );
    }
}

#[test]
fn lockfile_filenames_lists_all_four_in_precedence_order() {
    let eco = PypiEcosystem::new(Arc::new(HttpCache::new()));
    assert_eq!(
        eco.lockfile_filenames(),
        &["poetry.lock", "uv.lock", "pdm.lock", "Pipfile.lock"]
    );
}
