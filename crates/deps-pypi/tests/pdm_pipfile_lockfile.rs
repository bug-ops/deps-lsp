//! Acceptance tests for the `pdm.lock` and `Pipfile.lock` providers (#1926, spec 093).

#![allow(clippy::unwrap_used)]

use std::assert_matches;
use std::path::Path;
use std::sync::Arc;

use deps_core::lockfile::{LockFileProvider, ResolvedPackages, ResolvedSource};
use deps_core::{DepsError, EcosystemBase, HttpCache};
use deps_pypi::{PypiEcosystem, PypiLockParser};
use url::Url;

const PDM_LOCK: &str = r#"# This file is @generated by PDM.
# It is not intended for manual editing.

[metadata]
groups = ["default", "dev"]
strategy = ["inherit_metadata"]
lock_version = "4.5.0"
content_hash = "sha256:0000"

[[package]]
name = "requests"
version = "2.31.0"
requires_python = ">=3.7"
summary = "Python HTTP for Humans."
groups = ["default"]
dependencies = ["certifi>=2017.4.17"]

[[package]]
name = "Flask_Cors"
version = "4.0.0"
requires_python = ">=3.8"
groups = ["default"]

[[package]]
name = "mylib"
version = "0.1.0"
git = "https://github.com/example/mylib.git"
ref = "main"
revision = "0123456789abcdef0123456789abcdef01234567"
groups = ["default"]
"#;

const PDM_LOCK_V3: &str = r#"[metadata]
lock_version = "3.9.0"

[[package]]
name = "requests"
version = "2.31.0"
"#;

const PIPFILE_LOCK: &str = r#"{
    "_meta": {
        "hash": {"sha256": "0000"},
        "pipfile-spec": 6,
        "requires": {"python_version": "3.11"},
        "sources": [{"name": "pypi", "url": "https://pypi.org/simple", "verify_ssl": true}]
    },
    "default": {
        "requests": {"hashes": ["sha256:aa"], "index": "pypi", "version": "==2.31.0"},
        "Flask_Cors": {"hashes": [], "index": "pypi", "version": "==4.0.0"},
        "mylib": {"git": "https://github.com/example/mylib.git", "ref": "0123456789abcdef"},
        "localpkg": {"path": "./localpkg", "editable": true},
        "loose": {"version": ">=1.0"}
    },
    "develop": {
        "pytest": {"hashes": [], "index": "pypi", "version": "==7.4.0"}
    }
}"#;

const PIPFILE_LOCK_SPEC5: &str = r#"{
    "_meta": {"pipfile-spec": 5},
    "default": {"requests": {"version": "==2.31.0"}},
    "develop": {}
}"#;

async fn parse(dir: &Path, file: &str, content: &str) -> deps_core::Result<ResolvedPackages> {
    let path = dir.join(file);
    tokio::fs::write(&path, content).await.unwrap();
    PypiLockParser.parse_lockfile(&path).await
}

fn manifest_uri(dir: &Path) -> Url {
    Url::from_file_path(dir.join("pyproject.toml")).unwrap()
}

#[tokio::test]
async fn parse_lockfile_pdm_resolves_versions_with_normalized_names() {
    let dir = tempfile::tempdir().unwrap();
    let packages = parse(dir.path(), "pdm.lock", PDM_LOCK).await.unwrap();
    assert_eq!(packages.len(), 3);
    assert_eq!(packages.version("requests"), Some("2.31.0"));
    assert_eq!(packages.version("flask-cors"), Some("4.0.0"));
}

#[tokio::test]
async fn parse_lockfile_pdm_git_entry_is_git_source() {
    let dir = tempfile::tempdir().unwrap();
    let packages = parse(dir.path(), "pdm.lock", PDM_LOCK).await.unwrap();
    let mylib = packages.get("mylib").expect("git package present");
    assert_matches!(&mylib.source, ResolvedSource::Git { url, .. } if url == "https://github.com/example/mylib.git", "got {:?}",
        mylib.source);
}

#[tokio::test]
async fn parse_lockfile_pdm_registry_entry_is_registry_source() {
    let dir = tempfile::tempdir().unwrap();
    let packages = parse(dir.path(), "pdm.lock", PDM_LOCK).await.unwrap();
    assert!(packages.get("requests").unwrap().source.is_registry());
}

#[tokio::test]
async fn parse_lockfile_pdm_unsupported_lock_version_is_parse_error() {
    let dir = tempfile::tempdir().unwrap();
    let err = parse(dir.path(), "pdm.lock", PDM_LOCK_V3)
        .await
        .unwrap_err();
    assert_matches!(err, DepsError::ParseError { .. }, "got {err:?}");
    assert!(
        err.to_string().contains("lock_version") || err.to_string().contains("3.9"),
        "{err}"
    );
}

